import { readFile, writeFile } from "node:fs/promises";
import { basename, resolve } from "node:path";
import ts from "typescript";

const root = process.cwd();
const files = ["app/site.tsx", "app/experience.tsx", "app/company-pages.tsx"];
const sourceFiles = new Map();
const english = new Map();

const localeText = await readFile(resolve(root, "app/locale.ts"), "utf8");
const localeAst = ts.createSourceFile("locale.ts", localeText, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
function collectEnglish(node) {
  if (ts.isVariableDeclaration(node) && node.name.getText(localeAst) === "english" && node.initializer && ts.isObjectLiteralExpression(node.initializer)) {
    for (const property of node.initializer.properties) {
      if (!ts.isPropertyAssignment(property) || !ts.isStringLiteralLike(property.name) || !ts.isStringLiteralLike(property.initializer)) continue;
      english.set(property.name.text, property.initializer.text);
    }
  }
  ts.forEachChild(node, collectEnglish);
}
collectEnglish(localeAst);

const groups = {
  Site: "global",
  Catalog: "products",
  ProductDetail: "products",
  HomeProducts: "home",
  HomeExtras: "home",
  HomeServiceStory: "home",
  HomeRoomCards: "home",
  HomeHero: "home",
  HomeBenefits: "home",
  ContactBanner: "global",
  PageIntro: "global",
  FAQ: "faq",
  Services: "services",
  About: "about",
  Contact: "contact",
  Policies: "policies",
  FAQPage: "faq",
};

function ownerGroup(node, file) {
  let current = node.parent;
  while (current) {
    if (ts.isFunctionDeclaration(current) && current.name && groups[current.name.text]) return groups[current.name.text];
    if (ts.isArrowFunction(current) || ts.isFunctionExpression(current)) {
      let parent = current.parent;
      while (parent && parent !== node) {
        if (ts.isVariableDeclaration(parent) && ts.isIdentifier(parent.name) && groups[parent.name.text]) return groups[parent.name.text];
        if (ts.isPropertyAssignment(parent) && ts.isIdentifier(parent.name) && groups[parent.name.text]) return groups[parent.name.text];
        if (!ts.isParenthesizedExpression(parent) && !ts.isAsExpression(parent)) break;
        parent = parent.parent;
      }
    }
    current = current.parent;
  }
  return basename(file) === "site.tsx" ? "global" : "global";
}

const entries = new Map();

function copyEntryId(he, ar, en) {
  const source = JSON.stringify([he, ar, en ?? null]);
  let first = 2_166_136_261;
  let second = 3_266_489_917;
  for (let index = 0; index < source.length; index += 1) {
    const code = source.charCodeAt(index);
    first = Math.imul(first ^ code, 16_777_619);
    second = Math.imul(second ^ code, 2_246_822_519);
  }
  return `c-${(first >>> 0).toString(36)}${(second >>> 0).toString(36)}`;
}
for (const file of files) {
  const text = await readFile(resolve(root, file), "utf8");
  const ast = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
  sourceFiles.set(file, ast);
  function collectCalls(node) {
    if (ts.isCallExpression(node) && ts.isIdentifier(node.expression) && node.expression.text === "t" && node.arguments.length >= 2) {
      const [heArg, arArg, enArg] = node.arguments;
      if (ts.isStringLiteralLike(heArg) && ts.isStringLiteralLike(arArg) && (!enArg || ts.isStringLiteralLike(enArg))) {
        const he = heArg.text;
        const ar = arArg.text;
        const en = enArg?.text ?? english.get(he) ?? "";
        const id = copyEntryId(he, ar, enArg?.text);
        if (!entries.has(id)) entries.set(id, { id, group: ownerGroup(node, file), source: he, he, ar, en });
      }
    }
    ts.forEachChild(node, collectCalls);
  }
  collectCalls(ast);
}

const result = [...entries.values()].sort((a, b) => a.group.localeCompare(b.group) || a.source.localeCompare(b.source));
const output = `// Generated by npm run content:sync. Edit visitor-facing copy from /admin, not this file.\nexport const defaultCopy = ${JSON.stringify(result, null, 2)} as const;\n`;
await writeFile(resolve(root, "app/site-copy-defaults.ts"), output, "utf8");
console.log(`Generated ${result.length} multilingual copy entries from ${files.length} site components.`);
